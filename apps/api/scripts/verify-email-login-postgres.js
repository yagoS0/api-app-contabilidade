import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const pos=process.argv.indexOf('--url');
const url=new URL((pos>=0?process.argv[pos+1]:process.env.DATABASE_URL)||'invalid:');
if(!['postgresql:','postgres:'].includes(url.protocol)||!['127.0.0.1','localhost'].includes(url.hostname)||!/^\/[a-zA-Z0-9_]+_check$/.test(url.pathname))throw Error('Use apenas PostgreSQL local descartável terminado em _check.');
process.env.DATABASE_URL=url.href;
process.env.JWT_SECRET='email-login-disposable-test-'+randomUUID();
globalThis.fetch=async()=>{throw Error('Rede externa proibida neste ensaio');};
const {prisma}=await import('../src/infrastructure/db/prisma.js');
const {EmailLoginService}=await import('../src/application/auth/EmailLoginService.js');
const {authDigest}=await import('../src/application/auth/credentialSecurity.js');
const {PasswordResetService}=await import('../src/application/auth/PasswordResetService.js');
const {ClientSessionService}=await import('../src/application/auth/ClientSessionService.js');
const {AuthService}=await import('../src/application/auth/AuthService.js');
const prefix='email-check-'+randomUUID(), email=prefix+'@example.invalid', companyId=prefix+'-company';
const missing=prefix+'-missing@example.invalid';
let user;const now=new Date();
const time=n=>new Date(now.getTime()+n*61000);
try{
 user=await prisma.user.create({data:{email,passwordHash:'fixture-hash',status:'active',accountType:'CLIENT',role:'user'}});
 await prisma.portalClient.create({data:{id:companyId,cnpj:companyId,razao:'Fixture descartável'}});
 await prisma.companyClientUser.create({data:{companyId,userId:user.id,status:'ACTIVE',role:'OWNER'}});
 const requests=await Promise.all([1,2,3].map(()=>EmailLoginService.solicitar(email,{now})));
 assert.equal(requests.filter(r=>r.delivery).length,1,'envios simultâneos devem respeitar o intervalo');
 const first=requests.find(r=>r.delivery);
 const attempts=await Promise.all([1,2,3].map(()=>EmailLoginService.confirmar(first.challengeId,first.delivery.code,{now})));
 assert.equal(attempts.filter(Boolean).length,1,'um único consumo');
 assert.equal(await prisma.clientSession.count({where:{userId:user.id}}),1);
 const winner=attempts.find(Boolean), token=AuthService.generateToken(winner.user);
 assert.ok(await AuthService.resolveUserFromPayload(AuthService.verifyToken(token)));
 const rotations=await Promise.all([1,2].map(()=>ClientSessionService.rotate(winner.refreshToken)));
 assert.equal(rotations.filter(Boolean).length,1,'uma única rotação');
 await ClientSessionService.revokeByRefresh(rotations.find(Boolean).refreshToken,user.id);
 assert.equal(await AuthService.resolveUserFromPayload(AuthService.verifyToken(token)),null,'logout revoga também acesso vinculado');
 const second=await EmailLoginService.solicitar(email,{now:time(1)});
 const wrong=second.delivery.code==='00000000'?'11111111':'00000000';
 await Promise.all([1,2,3].map(()=>EmailLoginService.confirmar(second.challengeId,wrong,{now:time(1)})));
 await Promise.all([1,2].map(()=>EmailLoginService.confirmar(second.challengeId,wrong,{now:time(1)})));
 assert.equal(await EmailLoginService.confirmar(second.challengeId,second.delivery.code,{now:time(1)}),null,'cinco erros encerram o código');
 const third=await EmailLoginService.solicitar(email,{now:time(2)});
 await prisma.user.update({where:{id:user.id},data:{passwordHash:'changed-hash'}});
 assert.equal(await EmailLoginService.confirmar(third.challengeId,third.delivery.code,{now:time(2)}),null,'troca de senha invalida o código');
 const fourth=await EmailLoginService.solicitar(email,{now:time(3)});
 await prisma.companyClientUser.updateMany({where:{userId:user.id},data:{status:'REMOVED'}});
 assert.equal(await EmailLoginService.confirmar(fourth.challengeId,fourth.delivery.code,{now:time(3)}),null,'vínculo removido não autentica');
 const absent=await EmailLoginService.solicitar(missing,{now});
 assert.equal(absent.delivery,null);
 const reset=await PasswordResetService.criarPedido(user.id);
 const resetResults=await Promise.all([1,2].map(()=>PasswordResetService.redefinirSenha(reset.token,'NewTestPassword#2026')));
 assert.equal(resetResults.filter(r=>r.ok).length,1,'link de recuperação consumido uma única vez');
 console.log('PASS: concorrência de envio/código/refresh/reset, limites, logout e revogação em PostgreSQL real; zero e-mails enviados.');
}finally{
 await prisma.emailLoginChallenge.deleteMany({where:{emailKey:{in:[authDigest('email-login:'+email),authDigest('email-login:'+missing)]}}});
 if(user)await prisma.user.delete({where:{id:user.id}});
 await prisma.portalClient.deleteMany({where:{id:companyId}});
 await prisma.$disconnect();
}
