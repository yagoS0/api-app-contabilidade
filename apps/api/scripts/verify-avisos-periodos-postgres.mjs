import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import path from 'node:path';
import http from 'node:http';
import https from 'node:https';
import { registrarPendenciaDoPeriodo, processarAvisoDaEmissao, situacaoDoPeriodo } from '../src/application/notas/pendenciasDoPeriodo.js';
const [url, clientPath] = process.argv.slice(2);
const parsed = new URL(url);
assert(parsed.hostname === '127.0.0.1' && parsed.pathname === '/avisos_check' && parsed.username === 'avisos_test', 'Apenas banco descartável isolado.');
const bloquear = () => { throw Error('Rede fiscal proibida neste teste'); };
http.get = http.request = https.get = https.request = globalThis.fetch = bloquear;
const { PrismaClient } = createRequire(import.meta.url)(path.join(clientPath, 'index.js'));
const db = new PrismaClient({ datasources: { db: { url } } });
try {
 const client = await db.client.create({ data: { name: 'Teste', email: 'avisos@example.test', login: 'avisos', passwordHash: 'nao-utilizavel' } });
 const empresa = await db.company.create({ data: { clientId: client.id, razaoSocial: 'Empresa sintética', cnpj: '11111111000111', atividades: [] } });
 const portal = await db.portalClient.create({ data: { companyId: empresa.id, razao: 'Empresa sintética', cnpj: empresa.cnpj } });
 await db.apuracaoSnapshot.create({ data: { portalClientId: portal.id, competencia: '2026-09', rbt12: 1000, receitaPorTipo: {}, idempotencyKey: 'teste', dasSimuladoSerpro: 10, numeroDeclaracao: 'recibo-sintetico' } });
 const nota = { portalClientId: portal.id, competencia: '2026-09-01', chaveAcesso: 'chave-sintetica', valor: 1 };
 const invoice = await db.serviceInvoice.create({ data: { companyId: empresa.id, tomadorDoc: '11111111111', tomadorNome: 'Sintético', valorServicos: 1, competencia: new Date('2026-09-01'), chaveAcesso: nota.chaveAcesso, status: 'issued', revisaoPeriodoPendente: true } });
 await Promise.all(Array.from({ length: 10 }, () => registrarPendenciaDoPeriodo(db, { ...nota, serviceInvoiceId: invoice.id })));
 assert.equal(await db.pendenciaPosFechamento.count(), 1);
 await processarAvisoDaEmissao(db, invoice);
 assert.equal((await db.serviceInvoice.findUnique({ where: { id: invoice.id } })).revisaoPeriodoPendente, false);
 const capturada = await db.portalInvoice.create({ data: { clientId: portal.id, type: 'NFSE', chaveAcesso: nota.chaveAcesso, total: 1, competencia: new Date('2026-09-01') } });
 await registrarPendenciaDoPeriodo(db, { ...nota, notaId: capturada.id });
 let pend = await db.pendenciaPosFechamento.findFirst();
 assert.equal(pend.notaId, capturada.id); assert.equal(pend.serviceInvoiceId, invoice.id);
 await db.pendenciaPosFechamento.update({ where: { id: pend.id }, data: { resolvida: true, resolucaoMotivo: 'Receita já considerada', resolvidaByUserId: 'contador-sintetico', resolvidaAt: new Date() } });
 await registrarPendenciaDoPeriodo(db, { ...nota, notaId: capturada.id });
 assert.equal((await db.pendenciaPosFechamento.findUnique({ where: { id: pend.id } })).resolvida, true);
 await registrarPendenciaDoPeriodo(db, { ...nota, notaId: capturada.id, evento: 'evento_retroativo' });
 assert.equal(await db.pendenciaPosFechamento.count(), 2);
 await db.$disconnect(); await db.$connect();
 assert.equal(await db.pendenciaPosFechamento.count({ where: { resolvida: false } }), 1);
 assert.equal((await situacaoDoPeriodo(db, nota)).estado, 'TRANSMITIDA');
 assert.equal(await db.pendenciaPosFechamento.count({ where: { portalClientId: 'outra-empresa' } }), 0);
 console.log(JSON.stringify({ passed: true, concorrentes: 10, persistencia: true, deduplicacaoEmissaoCaptura: true, resolucaoPreservada: true, eventoSeparado: true, chamadasFiscais: 0 }));
} finally { await db.$disconnect(); }
