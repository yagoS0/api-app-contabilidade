import assert from 'node:assert/strict';
import { randomUUID, createCipheriv, createDecipheriv, randomBytes } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { criarRepositorioConsultaCnpj } from '../src/application/tomador/consultaCnpjRepository.js';
import { criarConsultaCnpjPersistente } from '../src/application/tomador/consultaCnpjPersistente.js';
const url = process.argv[2], parsed = new URL(url);
if (parsed.hostname !== '127.0.0.1' || parsed.pathname !== '/cnpj_check' || parsed.username !== 'cnpj_test') throw Error('Somente banco de teste isolado.');
const db = new PrismaClient({ datasources: { db: { url } } });
const key = randomBytes(32);
const cifrar = async value => { const iv = randomBytes(12), c = createCipheriv('aes-256-gcm',key,iv); const b=Buffer.concat([c.update(value,'utf8'),c.final()]); return Buffer.concat([iv,c.getAuthTag(),b]).toString('base64'); };
const decifrar = async value => { const b=Buffer.from(value,'base64'), d=createDecipheriv('aes-256-gcm',key,b.subarray(0,12)); d.setAuthTag(b.subarray(12,28)); return Buffer.concat([d.update(b.subarray(28)),d.final()]).toString('utf8'); };
let instante = new Date('2026-10-13T12:00:00Z');
const repo = () => criarRepositorioConsultaCnpj({ db,cifrar,decifrar,agora:()=>instante });
const cadastro = { ok:true,cnpj:'11222333000181',bruto:{ cnpj:'11222333000181',razao_social:'EMPRESA TESTE',logradouro:'TESTE',bairro:'CENTRO',municipio:'RIO',uf:'RJ',cep:'20040020',qsa:[{ nome_socio:'PRIVADO' }] } };
let checks = 0;
try {
  const r = repo(), req = { escritorioId:'a',cnpj:cadastro.cnpj,modalidade:'BASICA',requestKey:randomUUID() };
  assert.equal((await r.reservar(req)).autorizada,false); checks++;
  await db.$executeRaw`UPDATE "ConsultaCnpjOrcamento" SET "habilitado"=true,"limiteMicros"=3000000,"basicaMicros"=1000000,"empresaMicros"=2000000,"precosAte"=${new Date('2026-12-31T00:00:00Z')}`;
  const concorrentes = await Promise.all(Array.from({length:12},(_,i)=>repo().reservar({...req,escritorioId:`escopo-${i}`,requestKey:randomUUID()})));
  assert.equal(concorrentes.filter(x=>x.autorizada).length,3); checks++;
  const [uso] = await db.$queryRaw`SELECT SUM("custoMicros")::text AS total FROM "ConsultaCnpjReserva"`;
  assert.equal(uso.total,'3000000'); checks++;
  await db.$executeRaw`UPDATE "ConsultaCnpjOrcamento" SET "limiteMicros"=100000000`;
  const duplicadas = await Promise.all(Array.from({length:8},()=>repo().reservar(req)));
  assert.equal(duplicadas.filter(x=>x.autorizada).length,1); checks++;
  const reserva=duplicadas.find(x=>x.autorizada);
  await r.concluir({id:reserva.id,status:'INCERTA'});
  instante=new Date('2026-10-14T12:00:00Z');
  assert.equal((await r.reservar({...req,requestKey:randomUUID()})).autorizada,false); checks++;
  const keyCache={escopo:'empresa:teste',cnpj:cadastro.cnpj,modalidade:'BASICA'};
  const locks=await Promise.all(Array.from({length:8},()=>repo().adquirir(keyCache)));
  assert.equal(locks.filter(x=>x.lease).length,1); checks++;
  await r.salvar(locks.find(x=>x.lease),cadastro,60000);
  assert.deepEqual((await repo().adquirir(keyCache)).resultado,cadastro); checks++;
  assert.ok((await r.adquirir({...keyCache,escopo:'outra'})).lease); checks++;
  const [stored]=await db.$queryRaw`SELECT "conteudo" FROM "ConsultaCnpjCache" WHERE "escopo"='empresa:teste'`;
  assert.equal(stored.conteudo.includes('PRIVADO'),false); checks++;
  let chamadas=0;
  const consultar=criarConsultaCnpjPersistente({gratuito:async()=>{chamadas++;return cadastro;},repositorio:repo()});
  const hit=await consultar(cadastro.cnpj,{escopo:'empresa:teste'});
  assert.equal(hit.cache,true); assert.equal(chamadas,0); assert.equal(hit.bruto.qsa,undefined); checks++;
  instante=new Date(instante.getTime()+61000);
  const refreshed=await consultar(cadastro.cnpj,{escopo:'empresa:teste'});
  assert.equal(refreshed.ok,true); assert.equal(chamadas,1); checks++;
  const novoProcesso=criarConsultaCnpjPersistente({gratuito:async()=>{throw Error('cache não usado');},repositorio:repo()});
  assert.equal((await novoProcesso(cadastro.cnpj,{escopo:'empresa:teste'})).cache,true); checks++;
  // Lease antigo não sobrescreve dados gravados por uma execução nova.
  const old=await r.adquirir({ ...keyCache,escopo:'lease' });
  instante=new Date(instante.getTime()+31000);
  const fresh=await r.adquirir({ ...keyCache,escopo:'lease' });
  await r.salvar(fresh,cadastro,60000);
  assert.equal(await r.salvar(old,{ok:false},60000),0); checks++;
  await db.$executeRaw`UPDATE "ConsultaCnpjOrcamento" SET "precosAte"=${new Date('2020-01-01')}`;
  assert.equal((await r.reservar({...req,escritorioId:'nova',requestKey:randomUUID()})).autorizada,false); checks++;
  instante=new Date('2026-11-01T03:00:00Z');
  await db.$executeRaw`UPDATE "ConsultaCnpjOrcamento" SET "precosAte"=${new Date('2026-12-31')},"limiteMicros"=1000000`;
  assert.equal((await r.reservar({...req,escritorioId:'cadastro-novo',modalidade:'EMPRESA',requestKey:randomUUID()})).autorizada,false); checks++;
  assert.equal((await r.reservar({...req,escritorioId:'novembro',requestKey:randomUUID()})).autorizada,true); checks++;
  assert.equal((await r.reservar({...req,escritorioId:'novembro-2',requestKey:randomUUID()})).autorizada,false); checks++;
  assert.ok((await r.consumo()).some(x=>x.mes==='2026-11'&&x.custoMicros==='1000000')); checks++;
  console.log(JSON.stringify({ passed:true,checks, descricao:'PostgreSQL isolado: teto concorrente, reserva única, incerteza, cache cifrado, isolamento, TTL e lease.' }));
} finally { await db.$disconnect(); }
