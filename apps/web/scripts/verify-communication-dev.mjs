import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = 'http://127.0.0.1:5276';
const output = fileURLToPath(new URL('../../../test-evidence/comunicacao-dev/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
  page.setDefaultTimeout(60000);
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/*', route => new URL(route.request().url()).origin === base ? route.continue() : route.abort());
  await page.addInitScript(() => localStorage.setItem('portal_firm_access_token', 'mock-local-review'));
  await page.goto(base + '/companies?visao=tabela');
  await page.getByRole('button', { name: /^Acessar / }).first().click();
  await page.waitForURL('**/anotacoes');
  const path = new URL(page.url()).pathname.replace('/anotacoes', '');
  const nota = 'Nota interna da verificação local de comunicação';
  await page.getByLabel('Nova anotação sobre esta empresa').fill(nota);
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click();
  await page.getByText(nota, { exact: true }).waitFor();
  await page.reload();
  await page.getByText(nota, { exact: true }).waitFor();
  const article = page.locator('article').filter({ has: page.getByText(nota, { exact: true }) });
  await article.getByRole('button', { name: 'Fixar', exact: true }).click();
  await article.getByRole('button', { name: 'Desafixar' }).waitFor();
  await page.screenshot({ path: output + '/nota-persistida.png', fullPage: true });
  await page.goto(base + '/companies?visao=tabela');
  await page.getByRole('button', { name: /^Acessar / }).nth(1).click();
  await page.waitForURL('**/anotacoes');
  await page.getByLabel('Nova anotação sobre esta empresa').waitFor();
  assert.equal(await page.getByText(nota, { exact: true }).count(), 0);
  await page.goto(base + path + '/documentos');
  await page.getByLabel('Buscar documento').fill('CNPJ');
  assert.equal(await page.getByRole('button', { name: /^Baixar / }).count(), 1);
  await page.getByRole('button', { name: 'Limpar filtros' }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'revisao-local.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n% documento sintetico de teste local\n%%EOF') });
  await page.getByLabel('Tipo', { exact: true }).selectOption('OUTRO');
  await page.getByRole('button', { name: 'Guardar', exact: true }).click();
  await page.getByRole('button', { name: 'Baixar revisao-local.pdf' }).waitFor();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Baixar revisao-local.pdf' }).click();
  assert.equal((await download).suggestedFilename(), 'revisao-local.pdf');
  await page.getByLabel('Selecionar revisao-local.pdf').check();
  await page.getByRole('button', { name: 'Excluir', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('button', { name: 'Baixar revisao-local.pdf' }).count(), 0);
  await page.goto(base + path + '/anotacoes');
  await page.locator('article').filter({ has: page.getByText(nota, { exact: true }) }).getByRole('button', { name: 'Excluir', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir anotação', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.reload();
  await page.getByLabel('Nova anotação sobre esta empresa').waitFor();
  assert.equal(await page.getByText(nota, { exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  await writeFile(output + '/results.json', JSON.stringify({ notesCreateReloadPinDelete: true, companyIsolation: true, documentFilterUploadDownloadDelete: true, errors }, null, 2));
  console.log('Comunicação: criação, recarga, fixação, isolamento, filtro, upload, download e exclusão passaram.');
} finally { await browser.close(); }
